def fig_traffic(cfg, data):
    S = cfg.steps_per_day
    d = data["fit"]["demand"].reshape(-1, S, cfg.n_cells)
    wk = data["fit"]["weekend"].reshape(-1, S)[:, 0]
    hours = np.arange(S) * 24 / S
    fig, axes = plt.subplots(1, 4, figsize=(13, 3.0), sharey=True)
    for k, ax in enumerate(axes):
        cells = np.where(data["fit"]["true_type"] == k)[0]
        for mask, color, label in ((~wk, BLUE, "Sun–Thu (working days)"), (wk, ORANGE, "Fri–Sat (weekend)")):
            x = d[mask][:, :, cells]
            ax.fill_between(hours, np.percentile(x, 10, axis=(0, 2)), np.percentile(x, 90, axis=(0, 2)),
                            color=color, alpha=0.15, linewidth=0)
            ax.plot(hours, x.mean(axis=(0, 2)), color=color, label=label)
        ax.set_title(TYPES[k].capitalize())
        hour_axis(ax)
    axes[0].set_ylabel("traffic (1 = small-cell capacity)")
    axes[0].legend(loc="upper left", fontsize=9)
    fig.suptitle("Simulated traffic of the four area types (line = average, band = 10th–90th percentile)",
                 x=0.01, ha="left", fontsize=12, fontweight="bold", y=1.04)
    save(fig, "fig1_traffic.png")


def fig_clustering(R):
    u = R["unsupervised"]
    ks = [c["k"] for c in u["curve"]]
    fig, axes = plt.subplots(1, 3, figsize=(13, 3.4))
    ax = axes[0]
    ax.plot(ks, [c["distortion"] for c in u["curve"]], color=BLUE, marker="o", markersize=5)
    ax.set_title("Elbow curve")
    ax.set_xlabel("number of clusters K")
    ax.set_ylabel("mean squared distance to centroid")
    ax = axes[1]
    sil = [c["silhouette"] for c in u["curve"]]
    ax.plot(ks[1:], sil[1:], color=BLUE, marker="o", markersize=5)
    best = u["k"]
    ax.annotate(f"best: K = {best}", (best, sil[ks.index(best)]), textcoords="offset points", xytext=(12, -4), color=INK)
    ax.set_title("Silhouette score")
    ax.set_xlabel("number of clusters K")
    ax.set_ylabel("silhouette (higher = cleaner)")
    ax = axes[2]
    found, truth = np.array(u["cell_type"]), np.array(u["true_type"])
    for j, (cen, color) in enumerate(zip(u["centroids"], (BLUE, ORANGE, AQUA, YELLOW))):
        members = sorted({TYPES[t] for t in truth[found == j]})
        ax.plot(np.arange(24) + 0.5, cen, color=color, label=f"cluster {j + 1}: " + " + ".join(members))
    ax.set_title("Daily shape of each cluster found")
    ax.set_ylabel("traffic (day average = 1)")
    hour_axis(ax)
    ax.set_ylim(0, 4.2)
    ax.legend(fontsize=8.5, loc="upper left")
    fig.tight_layout()
    save(fig, "fig2_clustering.png")


def fig_anomaly(cfg, data, R):
    det = GaussianDetector().fit(data["fit"], cfg)
    det.select_threshold(data["val"])
    test = data["test"]
    flags, _ = det.detect(test)
    S = cfg.steps_per_day
    expected = det.profile[test["weekend"].astype(int), test["slot"]]
    fig, axes = plt.subplots(2, 1, figsize=(11, 5.2))
    for ax, kind, title in ((axes[0], FLASH, "A flash crowd (sudden extra traffic)"),
                            (axes[1], DROP, "A silent drop (traffic disappears)")):
        t_idx, cells = np.where(test["label"] == kind)
        # pick an event that happens in the middle of the day so the picture is easy to read
        ok = [(t, c) for t, c in zip(t_idx, cells)
              if 36 <= test["slot"][t] <= 76 and expected[t, c] > 0.25 and t >= S]
        t0, c = ok[0] if ok else (t_idx[0], cells[0])
        day = t0 // S
        sl = slice(max(day - 1, 0) * S, (day + 1) * S)
        x = np.arange(sl.stop - sl.start) / 4.0
        ax.plot(x, expected[sl, c], color=MUTED, linestyle=(0, (4, 3)), linewidth=1.5, label="usual traffic at this time")
        ax.plot(x, test["demand"][sl, c], color=BLUE, label="measured traffic")
        lab = test["label"][sl, c] > 0
        edges = np.flatnonzero(np.diff(np.r_[0, lab.astype(int), 0]))
        for a, b in zip(edges[::2], edges[1::2]):
            ax.axvspan(x[a], x[min(b, len(x) - 1)], color=YELLOW, alpha=0.18, linewidth=0,
                       label="true abnormal event" if a == edges[0] else None)
        f = flags[sl, c]
        ax.scatter(x[f], test["demand"][sl, c][f], s=34, color=RED, edgecolor=SURFACE, linewidth=1.2, zorder=3,
                   label="flagged by the detector")
        ax.set_title(title)
        ax.set_xlim(0, x[-1])
        ax.set_xticks(np.arange(0, x[-1] + 1, 6))
        ax.set_ylabel("traffic")
    axes[1].set_xlabel("hours (two consecutive test days of one cell)")
    axes[1].legend(ncol=2, fontsize=8.5, loc="upper left")
    a = R["unsupervised"]["anomaly"]["test"]
    fig.suptitle(f"Gaussian anomaly detector on unseen days: precision {a['precision']:.2f}, recall {a['recall']:.2f}, "
                 f"F1 {a['f1']:.2f}", x=0.01, ha="left", fontsize=12, fontweight="bold")
    fig.tight_layout()
    save(fig, "fig3_anomaly.png")


def fig_training(R, S):
    lam = S["selected_lam"]
    fig, axes = plt.subplots(1, 2, figsize=(11, 3.6))
    for types, color, label in ((True, BLUE, "with discovered traffic types"), (False, MUTED, "without traffic types")):
        runs = [r for r in R["dqn_runs"] if r["job"]["setting"] == "main" and r["job"]["lam"] == lam
                and r["job"]["use_types"] == types]
        ep = [h["epoch"] for h in runs[0]["history"]]
        for ax, key in ((axes[0], "saving_pct"), (axes[1], "unserved_pct")):
            y = np.array([[h[key] for h in r["history"]] for r in runs])
            ax.fill_between(ep, y.mean(0) - y.std(0), y.mean(0) + y.std(0), color=color, alpha=0.18, linewidth=0)
            ax.plot(ep, y.mean(0), color=color, label=label)
    axes[0].axhline(S["settings"]["main"]["load_aware"]["val"]["saving_pct"], color=ORANGE, linewidth=1.5,
                    linestyle=(0, (4, 3)))
    axes[0].text(axes[0].get_xlim()[1], S["settings"]["main"]["load_aware"]["val"]["saving_pct"],
                 " tuned rule", color=INK2, va="center", fontsize=8.5)
    axes[0].set_title("Energy saved on validation days")
    axes[0].set_ylabel("% saved vs always-on")
    axes[1].set_title("Unserved traffic on validation days")
    axes[1].set_ylabel("% of all traffic")
    for ax in axes:
        ax.set_xlabel("training epoch (14 simulated days each)")
    axes[1].legend(fontsize=9)
    fig.suptitle(f"DQN learning curves, mean ± std over 5 seeds (λ = {lam:.0f})", x=0.01, ha="left",
                 fontsize=12, fontweight="bold", y=1.03)
    save(fig, "fig4_training.png")


def draw_tradeoff(ax, R, S, compact=False):
    m = S["settings"]["main"]
    b = R["settings"]["main"]["baselines"]
    xmax = 0.26
    fr = sorted(b["frontier_load_aware"], key=lambda r: r["unserved_pct"])
    ax.plot([r["unserved_pct"] for r in fr], [r["saving_pct"] for r in fr], color=ORANGE, marker="o", markersize=3.5,
            linewidth=1.6, label="Load-aware threshold rule (all settings)")
    if not compact:
        fr = sorted(b["frontier_threshold"], key=lambda r: r["unserved_pct"])
        ax.plot([r["unserved_pct"] for r in fr], [r["saving_pct"] for r in fr], color=AQUA, marker="o", markersize=3.5,
                linewidth=1.6, label="Simple threshold rule (all settings)")
    for lam, g in S["main_by_lam"].items():
        d = g["types"]
        ax.errorbar(d["unserved_pct"][0], d["saving_pct"][0], xerr=d["unserved_pct"][1], yerr=d["saving_pct"][1],
                    color=BLUE, marker="o", markersize=8, capsize=2, linewidth=1.4, zorder=4,
                    label="DQN + traffic types (mean ± std, 5 seeds)" if lam == list(S["main_by_lam"])[0] else None)
        ax.annotate(f"λ={lam}", (d["unserved_pct"][0], d["saving_pct"][0]), textcoords="offset points",
                    xytext=(8, -12), color=INK2, fontsize=8.5)
    bound = m["bound"]
    ax.axhline(bound["saving_pct"], color=INK, linewidth=1.2, linestyle=(0, (4, 3)))
    ax.text(xmax, bound["saving_pct"], "limit with perfect knowledge of the future ", color=INK2, fontsize=8.5,
            ha="right", va="bottom")
    lo = min(r["saving_pct"] for r in b["frontier_load_aware"] if r["saving_pct"] > 0)
    ax.set_xlim(-0.006, xmax)
    ax.set_ylim(max(lo - 1.0, 24), bound["saving_pct"] + 1.2)
    ax.set_xlabel("unserved traffic (% of all traffic)   ← better")
    ax.set_ylabel("energy saved vs always-on (%)   better →")


