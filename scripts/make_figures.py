def fig_ablation(R, S):
    fig, axes = plt.subplots(1, 2, figsize=(11, 3.8))
    groups = (("main", "state held ≥ 1 hour"), ("short_hold", "state held ≥ 30 min"))
    for ax, key, title in ((axes[0], "saving_pct", "Energy saved (%)"), (axes[1], "unserved_pct", "Unserved traffic (%)")):
        ticks, names = [], []
        for gi, (setting, gname) in enumerate(groups):
            lam = S["settings"][setting]["lam"]
            for ti, (types, color, tname) in enumerate(((True, BLUE, "types"), (False, MUTED, "no types"))):
                runs = [r for r in R["dqn_runs"] if r["job"]["setting"] == setting and r["job"]["lam"] == lam
                        and r["job"]["use_types"] == types]
                y = np.array([r["test"][key] for r in runs])
                x0 = gi * 2.6 + ti
                ax.scatter(x0 + np.linspace(-0.16, 0.16, len(y)), y, s=46, color=color, edgecolor=SURFACE,
                           linewidth=1.2, zorder=3, label=("DQN with traffic types" if types else "DQN without traffic types") + " (one dot = one seed)" if gi == 0 else None)
                ax.hlines(y.mean(), x0 - 0.3, x0 + 0.3, color=INK, linewidth=1.6, zorder=4)
                ticks.append(x0)
                names.append(tname)
            ax.text(gi * 2.6 + 0.5, -0.2, gname, transform=ax.get_xaxis_transform(), ha="center", color=INK, fontsize=9.5)
        ax.set_xticks(ticks)
        ax.set_xticklabels(names, fontsize=9)
        ax.set_xlim(-0.7, 4.3)
        ax.grid(axis="x", visible=False)
        ax.set_title(title)
    axes[1].set_ylim(0, 0.68)
    axes[1].legend(fontsize=8.5, loc="upper right")
    fig.suptitle("Do the traffic types found by K-means help the agent?  (black bar = mean, test days)",
                 x=0.01, ha="left", fontsize=12, fontweight="bold", y=1.04)
    save(fig, "fig8_ablation.png")


def fig_day(cfg, data, R, S):
    lam = S["selected_lam"]
    types = discover_types(data["fit"], cfg)
    dqn = load_policy(os.path.join(RES, "models", f"main_lam{int(lam)}_types_seed0.npz"), cfg, types["onehot"])
    p = R["settings"]["main"]["baselines"]["load_aware"]["params"]
    test = data["test"]
    S_ = cfg.steps_per_day
    day = 8                                                  # a Tuesday in the test set
    sl = slice(day * S_ - cfg.n_lags, (day + 1) * S_ - cfg.n_lags)
    hours = np.arange(S_) / 4.0
    fig, axes = plt.subplots(2, 1, figsize=(10, 5.6), sharex=True, gridspec_kw={"height_ratios": [1.5, 1]})
    for pol, color, label in ((dqn, BLUE, "DQN"),
                              (LoadAwareThreshold(cfg, p["theta"], p["beta"]), ORANGE, "Load-aware rule"),
                              (Clairvoyant(cfg), INK, "Clairvoyant bound")):
        tr = run_policy(pol, test, cfg, trace=True)["trace"]
        axes[0].step(hours, tr["asleep"][sl], where="post", color=color, label=label,
                     linewidth=1.2 if color == INK else 2.0, linestyle=(0, (4, 3)) if color == INK else "-")
    axes[0].set_ylim(0, 12.5)
    axes[0].set_ylabel("small cells asleep (of 12)")
    axes[0].set_title("One working day in the test set: how many cells each controller lets sleep")
    axes[0].legend(ncol=3, fontsize=9, loc="lower left")
    t = slice(day * S_, (day + 1) * S_)
    total = test["demand"][t].sum(axis=1) + test["macro"][t]
    axes[1].fill_between(hours, 0, total, color=BLUE, alpha=0.18, linewidth=0)
    axes[1].plot(hours, total, color=BLUE)
    axes[1].axhline(cfg.macro_capacity, color=INK, linewidth=1.2, linestyle=(0, (4, 3)))
    axes[1].text(0.2, cfg.macro_capacity, "what the macro cell alone can carry", va="bottom", fontsize=8.5, color=INK2)
    axes[1].set_ylabel("total traffic")
    axes[1].set_title("Traffic offered to the whole network on that day")
    hour_axis(axes[1])
    fig.tight_layout()
    save(fig, "fig6_one_day.png")


