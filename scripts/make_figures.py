def summarise(R):
    """Collect the headline numbers once, so text and figures agree."""
    lam = R["selected_lam"]
    S = {"selected_lam": lam, "meets_limit": R.get("selected_lam_meets_limit", True), "settings": {}}

    def group(setting, lam_, types):
        return [r for r in R["dqn_runs"] if r["job"]["setting"] == setting
                and r["job"]["lam"] == lam_ and r["job"]["use_types"] == types]

    def stats(runs, key="test"):
        if not runs:
            return None
        return {m: ms([r[key][m] for r in runs]) for m in
                ("saving_pct", "unserved_pct", "energy_kwh_per_day", "switches_per_cell_day")} | {"n": len(runs)}

    for name, st in R["settings"].items():
        b = st["baselines"]
        lam_s = lam if name == "main" else 40.0
        S["settings"][name] = {
            "desc": st["desc"],
            "always_on": b["always_on"]["test"], "bound": b["clairvoyant"]["test"],
            "night": b["night"], "threshold": b["threshold"], "load_aware": b["load_aware"],
            "dqn": stats(group(name, lam_s, True)),
            "dqn_guard": stats(group(name, lam_s, True), "test_guard"),
            "dqn_notypes": stats(group(name, lam_s, False)),
            "dqn_val": stats(group(name, lam_s, True), "val"),
            "lam": lam_s,
        }
    S["main_by_lam"] = {str(int(l)): {"types": stats(group("main", l, True)), "notypes": stats(group("main", l, False)),
                                       "types_val": stats(group("main", l, True), "val")}
                        for l in sorted({r["job"]["lam"] for r in R["dqn_runs"] if r["job"]["setting"] == "main"})}
    return S


